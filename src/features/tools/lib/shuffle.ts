// Fisher-Yates — unbiased and the shared shuffle every tool (turn order,
// teams) needs, so a player's odds of landing anywhere are genuinely equal.
export function shuffle<T>(items: T[]): T[] {
  const result = [...items]
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[result[i], result[j]] = [result[j], result[i]]
  }
  return result
}
